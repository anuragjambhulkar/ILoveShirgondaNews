

async function run() {
    try {
        // 1. Initialize admin
        await fetch('http://localhost:3000/api/news'); // Just to trigger init

        // 2. Login
        const loginRes = await fetch('http://localhost:3000/api/auth/login', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ username: 'admin', password: 'admin123' })
        });
        const loginData = await loginRes.json();
        if (!loginData.token) {
            console.error('Login failed:', loginData);
            return;
        }
        const token = loginData.token;
        console.log('Got token:', token);

        // 3. Upload article
        const text = "अमेरिका आणि इस्राएलने इराणवर केलेल्या लष्करी कारवाईचे पडसाद थेट भारतात उमटू लागले असून, आंतरराष्ट्रीय शहर असलेले पुणेही त्याला अपवाद ठरलेले नाही.\n\nया हल्ल्याला प्रत्युत्तर म्हणून इराणने आखाती देशांमधील अमेरिकाच्या लष्करी तळांवर क्षेपणास्त्र व ड्रोन हल्ले केल्याने पश्चिम आशियातील परिस्थिती अधिकच चिघळली आहे. याचा थेट परिणाम आखाती देशांमध्ये नोकरी-व्यवसायानिमित्त गेलेल्या अनेक पुणेकरांवर होत असून, त्यांच्या सुरक्षेबाबत पुण्यातील कुटुंबीयांमध्ये चिंतेचे वातावरण निर्माण झाले आहे.\n\nआखाती देशांत कार्यरत असलेल्या पुणेकरांच्या कुटुंबीयांना या युद्धजन्य परिस्थितीमुळे असुरक्षिततेची भावना सतावत आहे. त्याचबरोबर खनिज तेलाचे दर वाढण्याची शक्यता वर्तवली जात असून, तेलदरवाढ झाल्यास पुण्यात पेट्रोल-डिझेल महाग होणे, वाहतूक खर्च वाढणे आणि अत्यावश्यक वस्तूंच्या किमती वाढण्याची भीती व्यक्त केली जात आहे. आंतरराष्ट्रीय बाजाराशी जोडलेले आयटी क्षेत्र आधीच नोकरीकपातीच्या संकटात असताना, हा तणाव वाढल्यास पुण्यातील आयटी उद्योगावरही नकारात्मक परिणाम होण्याची शक्यता आहे.\n\nदरम्यान, २८ फेब्रुवारी रोजी अमेरिका आणि इस्राएलने इराणमधील लष्करी व अण्वस्त्र कार्यक्रमाशी संबंधित ठिकाणांवर संयुक्त कारवाई करत 'ऑपरेशन एपिक फ्युरी' (काही आंतरराष्ट्रीय माध्यमांमध्ये 'लायन्स रोअर') सुरू केल्यानंतर पश्चिम आशिया निर्णायक वळणावर उभा राहिला आहे. अमेरिकन सेंट्रल कमांडच्या देखरेखीखाली झालेल्या या कारवाईत तेहरान, इस्फहान आणि इतर सामरिक ठिकाणांवर हल्ले झाल्याचे वृत्त आहे.\n\nया कारवाईत इराणचे सर्वोच्च नेते अयातुल्ला अली खामेनी यांचा मृत्यू झाल्याचा दावा करण्यात आला असून, संरक्षण विश्लेषकांच्या मते हा लष्करी तसेच राजकीय उद्देश साधण्याचा प्रयत्न असू शकतो. इराणी अधिकाऱ्यांनी नागरी हानी झाल्याचा आरोप करत इस्राएलसह कतार, बहरीन, यूएई आणि कुवेतमधील अमेरिकन तळांवर हल्ले केल्याचे सांगितले आहे.\n\nया घडामोडींवर रशिया आणि चीन यांनी तीव्र निषेध नोंदवला असून, संयुक्त राष्ट्रे यांनी सर्व पक्षांना संयम बाळगण्याचे आवाहन केले आहे.\n\nआंतरराष्ट्रीय तणावाचा परिणाम आता थेट पुणेकरांच्या दैनंदिन जीवनावर होण्याची भीती व्यक्त केली जात आहे.";

        const postRes = await fetch('http://localhost:3000/api/news', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'Authorization': `Bearer ${token}`
            },
            body: JSON.stringify({
                title: "Test Article",
                content: text,
                excerpt: text.substring(0, 100),
                category: "local",
                image: "",
                tags: []
            })
        });
        const postData = await postRes.text();
        console.log('Upload response status:', postRes.status);
        console.log('Upload response body:', postData);

    } catch (err) {
        console.error('Error:', err);
    }
}

run();
